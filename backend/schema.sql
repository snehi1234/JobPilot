create table if not exists public.profiles (
  user_sub      text primary key,          -- Google account subject id
  email         text,
  structured    jsonb not null default '{}'::jsonb,  -- Quick Details fields
  profile_text  text  not null default '',  -- extra typed notes
  resume_text   text  not null default '',  -- extracted text of the default resume
  resumes       jsonb not null default '[]'::jsonb,  -- all resumes: [{id,name,text,fileName,fileType,updatedAt,isDefault}]
  updated_at    timestamptz not null default now(),
  created_at    timestamptz not null default now()
);

-- Migration for databases created before multiple resumes were supported.
alter table public.profiles add column if not exists resumes jsonb not null default '[]'::jsonb;

-- The backend uses the service-role key and enforces per-user access in code
-- (by the verified Google token), so Row Level Security is not strictly
-- required. We still enable it and deny anon access as defense-in-depth.
alter table public.profiles enable row level security;

-- No policies for anon/authenticated roles → only the service-role key (used
-- by the backend) can read/write. This keeps data private.

-- Per-user monthly usage counters (protects shared AI quota from any single
-- heavy user starving everyone else).
create table if not exists public.usage_counters (
  user_sub   text not null,
  month      text not null,           -- "YYYY-MM", server-computed (UTC)
  count      integer not null default 0,
  updated_at timestamptz not null default now(),
  primary key (user_sub, month)
);

alter table public.usage_counters enable row level security;
-- No policies for anon/authenticated → service-role key only.

-- Atomically increments (and creates if missing) the counter for a user for
-- the given month, and returns the new count. Doing the increment inside a
-- single SQL statement avoids race conditions from concurrent requests.
create or replace function public.increment_usage(p_user_sub text, p_month text)
returns integer
language sql
as $$
  insert into public.usage_counters (user_sub, month, count, updated_at)
  values (p_user_sub, p_month, 1, now())
  on conflict (user_sub, month)
  do update set count = public.usage_counters.count + 1, updated_at = now()
  returning count;
$$;


-- Feedback reports sent from the extension ("Report a problem").
-- Read and triaged on the admin page (/admin); only the backend can access it.
create table if not exists public.feedback (
  id          bigserial primary key,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz,
  user_sub    text not null,
  email       text,                              -- shown to admins only if contact_ok
  contact_ok  boolean not null default false,
  type        text not null default 'other',     -- bug | wrong-answer | site | idea | other
  status      text not null default 'new',       -- new | in-progress | fixed | wont-fix
  message     text not null,
  details     jsonb not null default '{}'::jsonb -- site, version, field counts, last error
);
create index if not exists feedback_created_idx on public.feedback (created_at desc);
create index if not exists feedback_user_idx on public.feedback (user_sub, created_at);
alter table public.feedback enable row level security;
-- No policies → service-role key (backend) only.


-- Anonymous product-usage events (admin metrics). Only fixed event names and
-- small non-identifying properties (platform, counts, durations) are stored.
-- install_id is a random id generated by the extension; user_sub is set only
-- for signed-in users. Events older than 180 days are deleted by the backend.
create table if not exists public.events (
  id          bigserial primary key,
  created_at  timestamptz not null default now(),
  install_id  text not null,
  user_sub    text,
  name        text not null,
  version     text,
  props       jsonb not null default '{}'::jsonb
);
create index if not exists events_created_idx on public.events (created_at);
create index if not exists events_install_idx on public.events (install_id, created_at);
create index if not exists events_name_idx on public.events (name, created_at);
create index if not exists events_user_idx on public.events (user_sub);
alter table public.events enable row level security;
-- No policies → service-role key (backend) only.

-- One call returns everything the admin Metrics tab shows.
create or replace function public.admin_metrics(p_days integer default 30)
returns jsonb
language sql
stable
as $$
with
ev as (
  select install_id, user_sub, name, version, props, created_at,
         (created_at at time zone 'utc')::date as d
  from public.events
  where created_at >= now() - interval '180 days'
),
act as (
  select * from ev where name not in ('install', 'update', 'uninstall', 'uninstall_reason')
),
installs as (
  select install_id, min(created_at) as t from ev where name = 'install' group by install_id
),
uninstalls as (
  select install_id, min(created_at) as t from ev where name = 'uninstall' group by install_id
),
days as (
  select g::date as d
  from generate_series((now() at time zone 'utc')::date - (p_days - 1),
                       (now() at time zone 'utc')::date, interval '1 day') g
),
recent as (select * from ev where created_at >= now() - make_interval(days => p_days)),
num as (
  select name, install_id, props, created_at,
         case when jsonb_typeof(props->'fields') = 'number' then (props->>'fields')::numeric end as fields,
         case when jsonb_typeof(props->'seconds') = 'number' then (props->>'seconds')::numeric end as seconds,
         case when jsonb_typeof(props->'score') = 'number' then (props->>'score')::numeric end as score
  from recent
),
cohort as (select * from installs where t >= now() - make_interval(days => p_days)),
weeks as (
  select g::date as w
  from generate_series(date_trunc('week', now() - interval '7 weeks'), date_trunc('week', now()), interval '1 week') g
)
select jsonb_build_object(
  'generatedAt', now(),
  'days', p_days,
  'totals', jsonb_build_object(
    'installs', (select count(*) from installs),
    'uninstalls', (select count(*) from uninstalls),
    'seenInstalls', (select count(distinct install_id) from ev),
    'accounts', (select count(*) from public.profiles),
    'accountsWithResume', (select count(*) from public.profiles
                            where jsonb_array_length(resumes) > 0 or length(resume_text) > 0),
    'dau', (select count(distinct install_id) from act where created_at >= now() - interval '1 day'),
    'wau', (select count(distinct install_id) from act where created_at >= now() - interval '7 days'),
    'mau', (select count(distinct install_id) from act where created_at >= now() - interval '30 days'),
    'autofills', (select count(*) from num where name = 'autofill'),
    'fieldsFilled', (select coalesce(sum(fields), 0) from num where name = 'autofill'),
    'aiRequestsThisMonth', (select coalesce(sum(count), 0) from public.usage_counters
                            where month = to_char(now() at time zone 'utc', 'YYYY-MM'))
  ),
  'daily', (
    select jsonb_agg(jsonb_build_object(
      'd', days.d,
      'active', (select count(distinct install_id) from act where act.d = days.d),
      'installs', (select count(*) from installs where (installs.t at time zone 'utc')::date = days.d),
      'uninstalls', (select count(*) from uninstalls where (uninstalls.t at time zone 'utc')::date = days.d),
      'autofills', (select count(*) from ev where ev.name = 'autofill' and ev.d = days.d)
    ) order by days.d)
    from days
  ),
  'features', (
    select coalesce(jsonb_agg(jsonb_build_object('name', name, 'events', c, 'users', u) order by c desc), '[]'::jsonb)
    from (select name, count(*) c, count(distinct install_id) u from recent group by name) f
  ),
  'platforms', (
    select coalesce(jsonb_agg(jsonb_build_object('platform', p, 'fills', c, 'users', u, 'avgFields', af) order by c desc), '[]'::jsonb)
    from (select coalesce(props->>'platform', 'other') p, count(*) c, count(distinct install_id) u,
                 round(avg(fields), 1) af
          from num where name = 'autofill' group by 1) x
  ),
  'sessions', (
    select jsonb_build_object(
      'count', count(*),
      'avgMinutes', coalesce(round(avg(seconds) / 60.0, 1), 0),
      'medianMinutes', coalesce(round((percentile_cont(0.5) within group (order by seconds))::numeric / 60.0, 1), 0),
      'totalHours', coalesce(round(sum(seconds) / 3600.0, 1), 0))
    from num where name = 'panel_session' and seconds is not null
  ),
  'engagement', (
    select jsonb_build_object(
      'avgActiveDays', coalesce(round(avg(dcount), 1), 0),
      'avgEventsPerUser', coalesce(round(avg(ecount), 1), 0),
      'returningUsers', count(*) filter (where dcount >= 2),
      'activeUsers', count(*))
    from (select install_id, count(distinct d) dcount, count(*) ecount
          from act where created_at >= now() - make_interval(days => p_days) group by install_id) a
  ),
  'funnel', (
    select jsonb_build_object(
      'installed', count(*),
      'signedIn', count(*) filter (where exists (
        select 1 from ev e where e.install_id = c.install_id and (e.user_sub is not null or e.name = 'sign_in'))),
      'addedResume', count(*) filter (where exists (
        select 1 from ev e where e.install_id = c.install_id and e.name = 'resume_added')),
      'firstAutofill', count(*) filter (where exists (
        select 1 from ev e where e.install_id = c.install_id and e.name = 'autofill')),
      'returned', count(*) filter (where exists (
        select 1 from act e where e.install_id = c.install_id and e.created_at >= c.t + interval '1 day')),
      'uninstalled', count(*) filter (where exists (
        select 1 from uninstalls u where u.install_id = c.install_id)))
    from cohort c
  ),
  'retention', (
    select coalesce(jsonb_agg(jsonb_build_object(
      'week', weeks.w,
      'installs', (select count(*) from installs i where date_trunc('week', i.t) = weeks.w),
      'week1', (select count(*) from installs i where date_trunc('week', i.t) = weeks.w and exists (
        select 1 from act e where e.install_id = i.install_id
          and e.created_at >= i.t + interval '7 days' and e.created_at < i.t + interval '14 days')),
      'week2', (select count(*) from installs i where date_trunc('week', i.t) = weeks.w and exists (
        select 1 from act e where e.install_id = i.install_id
          and e.created_at >= i.t + interval '14 days' and e.created_at < i.t + interval '21 days'))
    ) order by weeks.w), '[]'::jsonb)
    from weeks
  ),
  'atsScores', (
    select jsonb_build_object('checks', count(*), 'avgScore', coalesce(round(avg(score), 0), 0))
    from num where name = 'ats_check' and score is not null
  ),
  'ratePrompt', (
    select coalesce(jsonb_object_agg(a, c), '{}'::jsonb)
    from (select coalesce(props->>'action', 'shown') a, count(*) c from recent where name = 'rate_prompt' group by 1) r
  ),
  'uninstallReasons', (
    select coalesce(jsonb_object_agg(r, c), '{}'::jsonb)
    from (select coalesce(props->>'reason', 'other') r, count(*) c from recent where name = 'uninstall_reason' group by 1) u
  ),
  'versions', (
    select coalesce(jsonb_agg(jsonb_build_object('version', v, 'users', c) order by c desc), '[]'::jsonb)
    from (select coalesce(version, '?') v, count(distinct install_id) c
          from act where created_at >= now() - interval '7 days' group by 1) vv
  )
);
$$;